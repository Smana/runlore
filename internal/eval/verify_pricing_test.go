// The rate cards below are one model and its cheaper verify tier, exactly 5x apart on
// both rates, so the arithmetic in the assertions is checkable by hand.
var (
	mainRates   = &investigate.Pricing{InputUSDPerMTok: 15, OutputUSDPerMTok: 75}
	verifyRates = &investigate.Pricing{InputUSDPerMTok: 3, OutputUSDPerMTok: 15}
)

// One loop call and one verify call, sized so the loop costs $0.04125 at mainRates
// and the verify pass $0.78375 there ($0.15675 at verifyRates). The verify prompt
// dwarfs the loop's because it replays the whole transcript for adversarial review.
var (
	loopCallUsage   = providers.Usage{InputTokens: 2250, OutputTokens: 100}
	verifyCallUsage = providers.Usage{InputTokens: 49_750, OutputTokens: 500}
)

const (
	trueCostOnOneModel = 0.825 // 0.04125 loop + 0.78375 verify, both at mainRates
	costAtVerifyRates  = 0.198 // 0.04125 loop + 0.15675 verify, verify at verifyRates
)

// onePassModel concludes on its first call and approves its own finding on the
// verify pass, reporting a distinct usage for each so the two can be priced apart.
type onePassModel struct{ calls int }

func (m *onePassModel) Complete(_ context.Context, req providers.CompletionRequest) (providers.CompletionResponse, error) {
	m.calls++
	if req.ToolChoice == "submit_verdicts" {
		return providers.CompletionResponse{
			Usage:     verifyCallUsage,
			ToolCalls: []providers.ToolCall{{ID: "v", Name: "submit_verdicts", Args: `{"verdicts":[{"index":0,"verdict":"keep","confidence":0.9}]}`}},
		}, nil
	}
	return providers.CompletionResponse{
		Usage: loopCallUsage,
		ToolCalls: []providers.ToolCall{{ID: "f", Name: "submit_findings",
			Args: `{"confidence":0.9,"root_causes":[{"summary":"bad image tag pushed by flux","confidence":0.9}]}`}},
	}, nil
}

// liveCostOf runs one live scenario under spend and returns the cost the campaign
// reported for it. --live is the arm that always verifies (LiveRunner sets
// Verify: true unconditionally), so every run of every scenario is affected.
func liveCostOf(t *testing.T, spend Spend) (cost float64, calls int) {
	t.Helper()
	m := &onePassModel{}
	lr := &LiveRunner{
		Model:     m,
		BaseTools: []investigate.Tool{fakeTool{name: "what_changed", out: "diff: tag v9.9.9"}},
		Steps:     &recordingSteps{}, Log: discardLog(), N: 1, Spend: spend,
	}
	scn := Scenario{ID: "priced"}
	scn.Trigger.Symptom = "pods not starting"
	res := lr.RunScenario(context.Background(), scn)
	if len(res.Runs) != 1 {
		t.Fatalf("want 1 run, got %d", len(res.Runs))
	}
	u := res.Runs[0].Investigation.Usage
	if !u.Priced {
		t.Fatal("the run reported no cost at all though Pricing is configured")
	}
	return u.CostUSD, m.calls
}

// TestEvalPricesVerifyAtTheRatesOfTheModelItActuallyCalled is the under-report
// direction, and the defect this file was written for.
//
// The eval harness hands each runner exactly ONE model and no verify override, so the
// adversarial pass runs on that same model. Carrying model.verify.pricing into the
// loop anyway priced those tokens at a rate card for a model the campaign never
// called: a run that truly cost $0.825 was reported at $0.198, 76% under — and
// max_cost_per_investigation, denominated in the same figure, was 76% too loose with
// it. internal/eval/spend.go states the opposite contract ("a case that would be cut
// short in production must be cut short here too").
func TestEvalPricesVerifyAtTheRatesOfTheModelItActuallyCalled(t *testing.T) {
	spend := Spend{Pricing: mainRates, Verifier: investigate.VerifyOn(nil, verifyRates)}
	cost, calls := liveCostOf(t, spend)

	if calls != 2 {
		t.Fatalf("want 2 completions (1 loop + 1 verify) on the ONE model the runner was given, "+
			"got %d — the fixture no longer exercises the verify pass", calls)
	}
	if math.Abs(cost-trueCostOnOneModel) > 1e-9 {
		under := (trueCostOnOneModel - cost) / trueCostOnOneModel * 100
		t.Errorf("the campaign reported $%.5f for a run that cost $%.5f on the single model it "+
			"drove — %.0f%% under. Verify's tokens were priced at model.verify.pricing, a rate "+
			"card for a model this run never called; they were generated by the main model and "+
			"must be priced at its rates", cost, trueCostOnOneModel, under)
	}
}

// TestEvalKeepsTheVerifyTiersOwnRatesWhenItHasItsOwnModel is the over-report
// direction, and the reason the fix is a pairing rather than a deletion.
//
// Dropping VerifyPricing outright would fix the campaign and break every production
// site, which DOES route the adversarial pass to a cheaper model (app/investigate.go,
// investigate_cmd.go, curator.go, demo.go all pair the two): those runs would then be
// billed at the expensive model's rates for tokens a cheap one generated. So the tier
// keeps its own rate card precisely when it has its own model — and only then.
func TestEvalKeepsTheVerifyTiersOwnRatesWhenItHasItsOwnModel(t *testing.T) {
	verifyM := &onePassModel{}
	spend := Spend{Pricing: mainRates, Verifier: investigate.VerifyOn(verifyM, verifyRates)}
	cost, mainCalls := liveCostOf(t, spend)

	if mainCalls != 1 || verifyM.calls != 1 {
		t.Fatalf("want the loop on the main model (1 call) and the verify pass on its own tier "+
			"(1 call), got main=%d verify=%d", mainCalls, verifyM.calls)
	}
	if math.Abs(cost-costAtVerifyRates) > 1e-9 {
		t.Errorf("a verify pass that really ran on its own cheaper model was reported at $%.5f, "+
			"want $%.5f — pricing it at the main model's rates over-reports every investigation "+
			"a production deployment with model.verify runs", cost, costAtVerifyRates)
	}
}

// TestAVerifyRateCardCannotOutliveTheModelItPrices pins the constructor's whole
// reason for existing: VerifyOn is the only way to build a tier, and it refuses to
// carry a rate card with no model attached. That is what makes the campaign bug
// unrepresentable rather than merely fixed at the three call sites that had it — the
// fourth runner, whenever someone writes it, cannot reintroduce it.
func TestAVerifyRateCardCannotOutliveTheModelItPrices(t *testing.T) {
	orphan := investigate.VerifyOn(nil, verifyRates)
	if orphan != (investigate.VerifyTier{}) {
		t.Errorf("VerifyOn(nil, rates) kept the rate card: %+v. With no separate model there is "+
			"no separate model to price, and those rates would be applied to tokens the MAIN "+
			"model generated", orphan)
	}
	paired := investigate.VerifyOn(&onePassModel{}, verifyRates)
	if paired == (investigate.VerifyTier{}) {
		t.Error("VerifyOn(model, rates) dropped a tier that has both halves")
	}
}

// verifyOnlyModel answers the adversarial pass and nothing else: if the loop's own
// turns reach it, its counter says so and the assertion below fails.
type verifyOnlyModel struct{ calls int }

func (m *verifyOnlyModel) Complete(_ context.Context, req providers.CompletionRequest) (providers.CompletionResponse, error) {
	m.calls++
	if req.ToolChoice != "submit_verdicts" {
		return providers.CompletionResponse{}, errNotTheVerifier
	}
	return providers.CompletionResponse{
		Usage:     verifyCallUsage,
		ToolCalls: []providers.ToolCall{{ID: "v", Name: "submit_verdicts", Args: `{"verdicts":[{"index":0,"verdict":"keep","confidence":0.9}]}`}},
	}, nil
}

var errNotTheVerifier = errTier("a loop turn reached the verify tier's model")

type errTier string

func (e errTier) Error() string { return string(e) }

// TestEveryEvalRunnerForwardsItsVerifyTier pins the plumbing the type alone cannot:
// that each runner actually HANDS its Spend.Verifier to the LoopInvestigator it
// builds. Spend.Verifier is empty for every campaign `lore eval` runs today, so a
// runner that silently dropped it would look identical — until the day someone gives
// the harness a real verify tier, and finds one arm quietly billing (and calling) the
// wrong model. The ceiling fields have the same guard in spend_test.go.
//
// The comparison runner is absent for a reason worth stating: ComparisonRunner's
// LoopInvestigator literal names no Verify at all, so the adversarial pass never runs
// on that arm and there is nothing to route. See the note in this package's Spend doc.
func TestEveryEvalRunnerForwardsItsVerifyTier(t *testing.T) {
	t.Run("live", func(t *testing.T) {
		tier := &verifyOnlyModel{}
		main := &onePassModel{}
		lr := &LiveRunner{
			Model:     main,
			BaseTools: []investigate.Tool{fakeTool{name: "what_changed", out: "diff: tag v9.9.9"}},
			Steps:     &recordingSteps{}, Log: discardLog(), N: 1,
			Spend: Spend{Pricing: mainRates, Verifier: investigate.VerifyOn(tier, verifyRates)},
		}
		scn := Scenario{ID: "routed"}
		scn.Trigger.Symptom = "pods not starting"
		lr.RunScenario(context.Background(), scn)
		if tier.calls != 1 {
			t.Errorf("the verify tier's model served %d completions, want 1: LiveRunner is not "+
				"forwarding Spend.Verifier, so verify ran on the main model and was billed at "+
				"the tier's rates anyway", tier.calls)
		}
	})

	t.Run("replay", func(t *testing.T) {
		tier := &verifyOnlyModel{}
		main := &onePassModel{}
		dir := t.TempDir()
		c := Case{
			Name:   "routed",
			Prompt: "pods not starting",
			// A catalog is what turns the replay arm's verify pass on (Runner.runOne sets
			// Verify: recall != nil). The entry deliberately does not match the prompt, so
			// recall does not fire and the loop runs to a normal conclusion first.
			CatalogDir: writeKBFixture(t, dir, "other-ns/unrelated"),
			Tools:      map[string]string{"what_changed": "diff: tag v9.9.9"},
			Expected:   Expected{MustContain: []string{"flux"}},
			dir:        dir,
		}
		r := &Runner{Model: main, Log: discardLog(),
			Spend: Spend{Pricing: mainRates, Verifier: investigate.VerifyOn(tier, verifyRates)}}
		r.runOne(context.Background(), c)
		if tier.calls != 1 {
			t.Errorf("the verify tier's model served %d completions, want 1: Runner is not "+
				"forwarding Spend.Verifier", tier.calls)
		}
	})
}
